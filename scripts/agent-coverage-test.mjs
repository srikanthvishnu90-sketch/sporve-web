#!/usr/bin/env node
// agent-coverage-test.mjs — doc 05 step 1: the coverage matrix, generated,
// never hand-maintained. Every doc-11 READ finding kind and WRITE job maps to
// the migration/function that implements it, or the script fails. Output:
// docs/agent/coverage.md (regenerated on every run).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const migDir = join(ROOT, "supabase", "migrations");
const sql = readdirSync(migDir).filter(f => f.endsWith(".sql"))
  .map(f => ({ f, text: readFileSync(join(migDir, f), "utf8") }));

const find = needle => {
  for (const { f, text } of sql) if (text.includes(needle)) return f;
  return null;
};

// READ layer — the finding codes doc 11 names (attendance/inquiry legs were
// REFUSED for lack of tables; they are listed as such, not hidden).
const READS = [
  ["overdue_summary", "'overdue_summary'"],
  ["missing_email", "'missing_email'"],
  ["credential_expiry", "'credential_expiry'"],
  ["waivers_unsigned", "'waivers_unsigned'"],
  ["lapsed_members", "'lapsed_members'"],
  ["reconciliation_drift", "'reconciliation_drift'"],
  ["refund_exposure", "'refund_exposure'"],
  ["staffing_gap", "'staffing_gap'"],
  ["booking_unconfirmed", "'booking_unconfirmed'"],
  ["schedule_conflict", "'schedule_conflict'"],
  ["roster_gap", "'roster_gap'"],
  ["missing_data", "'missing_data'"],
  ["waiver_drift", "'waiver_drift'"],
  ["idle_capacity", "'idle_capacity'"],
  ["waitlist_match", "'waitlist_match'"],
  ["camp_to_program", "'camp_to_program'"],
  ["collection_trend", "'collection_trend'"],
  ["org_structure", "'org_structure'"],
  ["discovery_lead (chat find_clients)", null, "supabase/functions/coach-command/index.ts", "discovery_lead"],
];

// WRITE layer — generators.
const WRITES = [
  ["dues chase ladder", "create or replace function public.generate_dues_obligations"],
  ["installment follow-ups (1/3/7)", "generate_installment_followups"],
  ["waiver follow-ups", "generate_waiver_followups"],
  ["practice reminders", "generate_practice_reminders"],
  ["eligibility report (B2)", "generate_eligibility_report"],
  ["reactivation (D1)", "generate_reactivation_drafts"],
  ["treasurer summary", "generate_treasurer_summary"],
  ["missing-info requests", "generate_missing_info_requests"],
  ["idle-capacity offers", "generate_idle_capacity_offers"],
  ["proposals (staff/schedule/payment-plan)", "generate_agent_proposals"],
  ["proposal APPLY executor", "apply_agent_proposal"],
];

const REFUSED = [
  ["attendance-based jobs", "no attendance table (owner decision pending)"],
  ["inquiries leg of reactivation", "no inquiries table"],
  ["D7 social scraping", "DECIDED-NOT-BUILDING (2026-09-01)"],
];

let missing = 0;
const rows = [];
for (const [name, needle, file, marker] of READS) {
  let where = needle ? find(needle) : null;
  if (!where && file && marker) {
    try { if (readFileSync(join(ROOT, file), "utf8").includes(marker)) where = file; } catch {}
  }
  if (!where) missing++;
  rows.push(`| READ | ${name} | ${where ?? "**NOT BUILT**"} |`);
}
for (const [name, needle] of WRITES) {
  const where = find(needle);
  if (!where) missing++;
  rows.push(`| WRITE | ${name} | ${where ?? "**NOT BUILT**"} |`);
}
for (const [name, why] of REFUSED) rows.push(`| REFUSED | ${name} | ${why} |`);

const md = `# Agent coverage matrix
> GENERATED by \`scripts/agent-coverage-test.mjs\` — do not edit by hand.
> Regenerated ${new Date().toISOString().slice(0, 10)}. ${missing === 0 ? "Every listed job is implemented." : missing + " job(s) missing."}

| layer | job | implemented in |
|---|---|---|
${rows.join("\n")}
`;
mkdirSync(join(ROOT, "docs", "agent"), { recursive: true });
writeFileSync(join(ROOT, "docs", "agent", "coverage.md"), md);
console.log(`agent coverage: ${READS.length + WRITES.length - missing}/${READS.length + WRITES.length} implemented, ${REFUSED.length} refused-by-decision`);
if (missing > 0) { console.error(`FAIL: ${missing} expected agent job(s) have no implementation`); process.exit(1); }
